"""SCRUM-205: model ORM runs sama dengan migrasi 16014b26f0bf, dan migrasinya bisa dibalik.

Model dibandingkan lewat alembic check, jadi lewat migrations/env.py yang sama
dengan autogenerate. Model yang hilang atau berbeda membuat revisi berikutnya
diam-diam mengusulkan DROP tabel pengukuran. Hanya tabel SCRUM-205 yang diperiksa.

Tes downgrade menurunkan database ke revisi sebelumnya lalu menaikkannya lagi,
dan fixture selalu mengembalikannya ke head. Dilewati kalau TEST_POSTGRES_URL kosong.
"""

import os
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, text

from app.shared.config import get_settings

POSTGRES_URL = os.environ.get("TEST_POSTGRES_URL", "")
SEBELUM = "a1f8c7e3d092"  # pragma: allowlist secret (revision id)
ROOT = Path(__file__).resolve().parents[2]

TABEL_205 = {
    "measurement_sessions",
    "measurement_session_suites",
    "session_product_copies",
    "case_snapshots",
    "case_snapshot_items",
    "attempts",
}
FUNGSI_205 = {
    "measurement_sessions_forbid_delete",
    "case_snapshots_forbid_change",
    "attempts_protect_answer",
}
ENUM_205 = {
    "measurement_purpose_enum",
    "measurement_session_type_enum",
    "measurement_split_filter_enum",
    "measurement_session_status_enum",
    "attempt_source_enum",
    "attempt_status_enum",
}

pytestmark = [
    pytest.mark.postgres,
    pytest.mark.skipif(not POSTGRES_URL, reason="TEST_POSTGRES_URL tidak diisi"),
]


@pytest.fixture
def alembic_cfg(monkeypatch):
    """Alembic membaca URL dari settings (migrations/env.py), jadi arahkan ke database tes."""
    monkeypatch.setenv("DATABASE_URL", POSTGRES_URL)
    get_settings.cache_clear()
    cfg = Config(str(ROOT / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "migrations"))
    yield cfg
    command.upgrade(cfg, "head")
    get_settings.cache_clear()


def _tabel(diff) -> str | None:
    """Nama tabel dari satu operasi autogenerate. modify_* datang sebagai daftar."""
    if isinstance(diff, list):
        diff = diff[0]
    objek = diff[1]
    if hasattr(objek, "table"):
        return objek.table.name
    if hasattr(objek, "name") and diff[0].endswith("_table"):
        return objek.name
    return diff[2]


def _objek_205(koneksi) -> dict[str, set[str]]:
    return {
        "tabel": set(
            koneksi.execute(
                text("SELECT tablename FROM pg_tables WHERE tablename = ANY(:nama)"),
                {"nama": list(TABEL_205)},
            ).scalars()
        ),
        "fungsi": set(
            koneksi.execute(
                text("SELECT proname FROM pg_proc WHERE proname = ANY(:nama)"),
                {"nama": list(FUNGSI_205)},
            ).scalars()
        ),
        "enum": set(
            koneksi.execute(
                text("SELECT typname FROM pg_type WHERE typname = ANY(:nama)"),
                {"nama": list(ENUM_205)},
            ).scalars()
        ),
    }


def test_model_runs_sama_dengan_migrasi(alembic_cfg):
    """Autogenerate tidak menemukan perbedaan apa pun pada tabel SCRUM-205."""
    # Act
    try:
        command.check(alembic_cfg)
        beda = []
    except AutogenerateDiffsDetected as info:
        beda = [diff for diff in info.diffs if _tabel(diff) in TABEL_205]

    # Assert
    assert beda == []


def test_downgrade_menghapus_semua_objek_lalu_upgrade_mengembalikannya(alembic_cfg):
    """Rollback migrasi 205 bersih: tabel, fungsi trigger, dan enum hilang, lalu kembali."""
    mesin = create_engine(POSTGRES_URL)
    try:
        # Act
        command.downgrade(alembic_cfg, SEBELUM)
        with mesin.connect() as koneksi:
            setelah_turun = _objek_205(koneksi)
        command.upgrade(alembic_cfg, "head")
        with mesin.connect() as koneksi:
            setelah_naik = _objek_205(koneksi)
    finally:
        mesin.dispose()

    # Assert
    assert setelah_turun == {"tabel": set(), "fungsi": set(), "enum": set()}
    assert setelah_naik == {"tabel": TABEL_205, "fungsi": FUNGSI_205, "enum": ENUM_205}

def _downgrade(conn, berkas: str) -> None:
    spec = importlib.util.spec_from_file_location(f"migrasi_{berkas[:12]}", VERSIONS / berkas)
    modul = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(modul)
    with Operations.context(MigrationContext.configure(conn)):
        modul.downgrade()


def _tabel(diff) -> str | None:
    """Nama tabel dari satu operasi autogenerate. modify_* datang sebagai daftar."""
    if isinstance(diff, list):
        diff = diff[0]
    objek = diff[1]
    if hasattr(objek, "table"):
        return objek.table.name
    if hasattr(objek, "name") and diff[0].endswith("_table"):
        return objek.name
    return diff[2]


def _objek(koneksi) -> dict[str, set[str]]:
    def _nama(sql: str, nama: set[str]) -> set[str]:
        return set(koneksi.execute(text(sql), {"nama": list(nama)}).scalars())

    return {
        "tabel": _nama("SELECT tablename FROM pg_tables WHERE tablename = ANY(:nama)", TABEL),
        "fungsi": _nama("SELECT proname FROM pg_proc WHERE proname = ANY(:nama)", FUNGSI),
        "enum": _nama("SELECT typname FROM pg_type WHERE typname = ANY(:nama)", ENUM),
    }


def _sesi_dengan_hasil(conn, admin_id) -> uuid.UUID:
    sesi = buat_sesi(conn, buat_produk(conn, admin_id), admin_id)
    run = buat_run(conn, sesi, buat_versi_aktif(conn, admin_id), admin_id)
    jalankan_run(conn, run)
    return buat_hasil(conn, run, buat_percobaan(conn, sesi, admin_id))



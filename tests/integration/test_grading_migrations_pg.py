def test_model_grading_sama_dengan_migrasi(alembic_cfg):
    """Positif: autogenerate tidak menemukan perbedaan apa pun pada tabel grading."""
    try:
        command.check(alembic_cfg)
        beda = []
    except AutogenerateDiffsDetected as info:
        beda = [diff for diff in info.diffs if _tabel(diff) in TABEL]

    assert beda == []


# --- Downgrade tanpa data ---------------------------------------------------------


def test_downgrade_menghapus_semua_objek_grading_lalu_upgrade_mengembalikannya(alembic_cfg):
    """Positif: rollback ketiga migrasi bersih, lalu upgrade mengembalikan semuanya."""
    mesin = create_engine(POSTGRES_URL)
    try:
        command.downgrade(alembic_cfg, SEBELUM)
        with mesin.connect() as koneksi:
            setelah_turun = _objek(koneksi)
        command.upgrade(alembic_cfg, "head")
        with mesin.connect() as koneksi:
            setelah_naik = _objek(koneksi)
            kode = koneksi.execute(
                text("SELECT count(*) FROM reason_codes WHERE is_proposed")
            ).scalar_one()
    finally:
        mesin.dispose()

    assert setelah_turun == {"tabel": set(), "fungsi": set(), "enum": set()}
    assert setelah_naik == {"tabel": TABEL, "fungsi": FUNGSI, "enum": ENUM}
    assert kode == 4



def test_upgrade_mengosongkan_penilai_yatim_dan_mencatat_jumlahnya(conn, admin_id, caplog):
    """Positif: sesi Menunggu, sesi yang sudah selesai, dan grading run dengan uuid bebas
    dikosongkan. Sesi tanpa penilai tidak tersentuh dan tidak ikut dihitung."""
    _jalankan(conn, "downgrade")
    produk = buat_produk(conn, admin_id)
    menunggu = buat_sesi(conn, produk, admin_id, judge_provider_id=uuid.uuid4())
    selesai = buat_sesi(conn, produk, admin_id, judge_provider_id=uuid.uuid4())
    ubah_status(conn, selesai, "running")
    ubah_status(conn, selesai, "finished")
    tanpa_penilai = buat_sesi(conn, produk, admin_id)
    run = buat_run(
        conn, selesai, buat_versi_aktif(conn, admin_id), admin_id, judge_provider_id=uuid.uuid4()
    )
    jalankan_run(conn, run)

    with caplog.at_level(logging.WARNING, logger="alembic.runtime.migration"):
        _jalankan(conn, "upgrade")

    assert _penilai_sesi(conn, menunggu) is None
    assert _penilai_sesi(conn, selesai) is None
    assert _penilai_sesi(conn, tanpa_penilai) is None
    assert _penilai_run(conn, run) is None
    assert "2 measurement_sessions" in caplog.text
    assert "1 grading_runs" in caplog.text


def test_upgrade_tanpa_nilai_yatim_tetap_mencatat_nol(conn, caplog):
    """Edge: database dev normal (FE hanya mengirim null), log tetap menyebut 0."""
    _jalankan(conn, "downgrade")

    with caplog.at_level(logging.WARNING, logger="alembic.runtime.migration"):
        _jalankan(conn, "upgrade")

    assert "0 measurement_sessions" in caplog.text
    assert "0 grading_runs" in caplog.text


def test_trigger_penjaga_hidup_lagi_setelah_upgrade(conn, admin_id):
    """Negatif: trigger hanya dimatikan selama pengosongan. Sesudah upgrade, penilai sesi
    yang sudah selesai dan penilai grading run tetap tidak bisa diubah."""
    _jalankan(conn, "downgrade")
    _jalankan(conn, "upgrade")
    penilai = buat_penilai(conn, admin_id)
    sesi = buat_sesi(conn, buat_produk(conn, admin_id), admin_id)
    ubah_status(conn, sesi, "running")
    ubah_status(conn, sesi, "finished")
    run = buat_run(conn, sesi, buat_versi_aktif(conn, admin_id), admin_id)

    sesi_ditolak = galat(
        conn,
        lambda: conn.execute(
            text("UPDATE measurement_sessions SET judge_provider_id = :p WHERE id = :id"),
            {"p": penilai, "id": sesi},
        ),
    ).sqlstate
    run_ditolak = galat(
        conn,
        lambda: conn.execute(
            text("UPDATE grading_runs SET judge_provider_id = :p WHERE id = :id"),
            {"p": penilai, "id": run},
        ),
    ).sqlstate

    assert sesi_ditolak == INSUFFICIENT_PRIVILEGE
    assert run_ditolak == INSUFFICIENT_PRIVILEGE



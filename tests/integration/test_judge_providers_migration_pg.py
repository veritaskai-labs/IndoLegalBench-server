def _migrasi():
    spec = importlib.util.spec_from_file_location("migrasi_judge_providers", VERSIONS / BERKAS)
    modul = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(modul)
    return modul


def _jalankan(conn, langkah: str) -> None:
    with Operations.context(MigrationContext.configure(conn)):
        getattr(_migrasi(), langkah)()


def _objek(koneksi) -> dict:
    tabel = koneksi.execute(
        text("SELECT count(*) FROM pg_tables WHERE tablename = 'judge_providers'")
    ).scalar_one()
    fk = set(
        koneksi.execute(
            text("SELECT conname FROM pg_constraint WHERE conname = ANY(:nama)"), {"nama": list(FK)}
        ).scalars()
    )
    return {"tabel": tabel, "fk": fk}


def _penilai_sesi(conn, sesi_id):
    return conn.execute(
        text("SELECT judge_provider_id FROM measurement_sessions WHERE id = :id"), {"id": sesi_id}
    ).scalar_one()


def _penilai_run(conn, run_id):
    return conn.execute(
        text("SELECT judge_provider_id FROM grading_runs WHERE id = :id"), {"id": run_id}
    ).scalar_one()



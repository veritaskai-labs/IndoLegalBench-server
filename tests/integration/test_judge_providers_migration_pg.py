# --- Upgrade dan downgrade tanpa data ---------------------------------------------


def test_downgrade_menghapus_tabel_dan_fk_lalu_upgrade_mengembalikannya(alembic_cfg):
    mesin = create_engine(POSTGRES_URL)
    try:
        command.downgrade(alembic_cfg, SEBELUM)
        with mesin.connect() as koneksi:
            setelah_turun = _objek(koneksi)
        command.upgrade(alembic_cfg, "head")
        with mesin.connect() as koneksi:
            setelah_naik = _objek(koneksi)
    finally:
        mesin.dispose()

    assert setelah_turun == {"tabel": 0, "fk": set()}
    assert setelah_naik == {"tabel": 1, "fk": FK}



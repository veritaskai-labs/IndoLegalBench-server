def test_jawaban_asli_tidak_bisa_dihapus(conn, sesi):
    sesi_id, admin_id = sesi
    item_id = buat_item_snapshot(conn, sesi_id, admin_id)
    percobaan_id = conn.execute(
        text(
            "INSERT INTO attempts (id, session_id, snapshot_item_id, repetition_no, source) "
            "VALUES (:id, :sesi, :item, 1, 'automatic') RETURNING id"
        ),
        {"id": uuid.uuid4(), "sesi": sesi_id, "item": item_id},
    ).scalar_one()

    kode = sqlstate_penolakan(conn, "DELETE FROM attempts WHERE id = :id", {"id": percobaan_id})

    assert kode == INSUFFICIENT_PRIVILEGE


def _downgrade(conn) -> None:
    spec = importlib.util.spec_from_file_location("migrasi_327_score_files", MIGRASI)
    modul = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(modul)
    with Operations.context(MigrationContext.configure(conn)):
        modul.downgrade()


def _tabel_ada(conn) -> bool:
    return conn.execute(text("SELECT to_regclass(:t) IS NOT NULL"), {"t": TABEL}).scalar_one()


def test_downgrade_ditolak_selama_ada_berkas_tersimpan(conn, sesi):
    _simpan(conn, *sesi)

    with pytest.raises(RuntimeError, match=PESAN_TOLAK_DOWNGRADE):
        _downgrade(conn)

    assert _tabel_ada(conn)


def test_downgrade_tabel_kosong_tetap_bisa(conn):
    if conn.execute(text(f"SELECT EXISTS (SELECT 1 FROM {TABEL})")).scalar_one():
        pytest.skip("basis data ini sudah berisi berkas skor; downgrade memang harus ditolak")

    _downgrade(conn)

    assert not _tabel_ada(conn)


